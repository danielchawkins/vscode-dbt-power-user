const HEADER =
  "# Generated by scripts/parity/print-fixtures.mjs from packages/graph-layout/src. Do not edit by hand.";

// Seeds as the TypeScript functions see them after `seed >>> 0`: the Rust side takes the same u32.
const SEEDS = [0, 1, 42, 123456789, 0x9e3779b9, 0x7fffffff, 0xffffffff];
const DRAWS = 16;
const SHUFFLE_LENGTHS = [0, 1, 2, 7, 64];

function printRandom() {
  const lines = [
    HEADER,
    "# random <seed> <draw>...: each draw is String(x) of seededRandom(seed)() in [0, 1).",
  ];
  for (const seed of SEEDS) {
    const next = seededRandom(seed);
    const draws = Array.from({ length: DRAWS }, () => String(next()));
    lines.push(["random", String(seed >>> 0), ...draws].join(" "));
  }
  lines.push(
    "# shuffle <seed> <length> <permutation>: shuffled(0..length, seededRandom(seed)), comma-separated.",
  );
  for (const seed of SEEDS) {
    for (const length of SHUFFLE_LENGTHS) {
      const items = Array.from({ length }, (_, i) => i);
      const out = shuffled(items, seededRandom(seed));
      lines.push(
        [
          "shuffle",
          String(seed >>> 0),
          String(length),
          out.join(",") || "-",
        ].join(" "),
      );
    }
  }
  return lines;
}

function printBudget() {
  const lines = [
    HEADER,
    "# budget <effort> <field>=<count>...: budgetOf({ effort }) in the field order of budget.ts.",
  ];
  for (const effort of ["fast", "balanced", "thorough"]) {
    const budget = budgetOf({ effort });
    const fields = Object.entries(budget).map(
      ([name, count]) => `${name}=${count}`,
    );
    lines.push(["budget", effort, ...fields].join(" "));
  }
  const fallback = budgetOf({});
  lines.push(
    [
      "budget",
      "unset",
      ...Object.entries(fallback).map(([name, count]) => `${name}=${count}`),
    ].join(" "),
  );
  return lines;
}

const FENWICK_SEEDS = [1, 7, 42];
const FENWICK_SIZES = [1, 2, 3, 8, 13, 64, 200];

/**
 * A Fenwick tree under fractional updates: for each seed and size, `4 * size + 10` updates, each drawing an index
 * `u32 % size` and then a delta `random() * 4 - 1` (fractional, some negative), then every prefix in bits.
 * The Rust test replays the same draws, so a change in the order of the summation shows in the bits.
 */
function printFenwick() {
  const lines = [
    HEADER,
    "# fenwick <seed> <size> <prefix>...: prefix(end) for end 0 to size after the updates, as IEEE bits, comma-separated.",
  ];
  for (const seed of FENWICK_SEEDS) {
    for (const size of FENWICK_SIZES) {
      const random = seededRandom(seed);
      const tree = new Fenwick(size);
      for (let k = 0; k < 4 * size + 10; k++) {
        // The draw times 2^32 is the u32 that `Mulberry32::next_u32` returns, so the index is the same integer.
        const index = Math.floor(random() * 4294967296) % size;
        tree.add(index, random() * 4 - 1);
      }
      const prefixes = Array.from({ length: size + 1 }, (_, end) =>
        bitsHex(tree.prefix(end)),
      );
      lines.push(
        ["fenwick", String(seed), String(size), prefixes.join(",")].join(" "),
      );
    }
  }
  return lines;
}

function hex(bytes) {
  return Buffer.from(bytes).toString("hex");
}

