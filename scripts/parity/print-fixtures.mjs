// Prints the TypeScript oracle values that the Rust crates are tested against. Contributor
// tooling only: it runs under Node's type stripping, imports the TypeScript sources directly, and writes to stdout.
//
//   mise exec -- node scripts/parity/print-fixtures.mjs random > crates/graph-layout/fixtures/parity/random.txt
//   mise exec -- node scripts/parity/print-fixtures.mjs budget > crates/graph-layout/fixtures/parity/budget.txt
//   mise exec -- node scripts/parity/print-fixtures.mjs frame > crates/graph-layout/fixtures/parity/frame.txt
//   mise exec -- node scripts/parity/print-fixtures.mjs solve-cases > crates/graph-layout/fixtures/parity/solve-cases.txt
//   mise exec -- node scripts/parity/print-fixtures.mjs solve-random > crates/graph-layout/fixtures/parity/solve-random.txt
//
// The fixtures are committed; regenerate them only when the TypeScript source changes on purpose.

import { register } from "node:module";

// The hook must be registered before the sources load, so their imports are resolved after it: they are imported
// below, not statically.
register("./ts-resolve.mjs", import.meta.url);
const { budgetOf } = await import("../../packages/graph-layout/src/budget.ts");
const { encodeGraph, encodeLayout } =
  await import("../../packages/graph-layout/src/frame.ts");
const { seededRandom, shuffled } =
  await import("../../packages/graph-layout/src/random.ts");
const { emptyLayout, goldenGraph, goldenLayout } =
  await import("../../packages/graph-layout/src/testing/frameGolden.ts");
const { solveSeparations } =
  await import("../../packages/graph-layout/src/solve/vpsc.ts");
const { cases } =
  await import("../../packages/graph-layout/src/testing/msaglCases.ts");
const { chainCases } =
  await import("../../packages/graph-layout/src/testing/msaglChains.ts");

const HEADER =
  "# Generated by scripts/parity/print-fixtures.mjs from packages/graph-layout/src. Do not edit by hand.";

// Seeds as the TypeScript functions see them after `seed >>> 0`: the Rust side takes the same u32.
const SEEDS = [0, 1, 42, 123456789, 0x9e3779b9, 0x7fffffff, 0xffffffff];
const DRAWS = 16;
const SHUFFLE_LENGTHS = [0, 1, 2, 7, 64];

function printRandom() {
  const lines = [
    HEADER,
    "# random <seed> <draw>...: each draw is String(x) of seededRandom(seed)() in [0, 1).",
  ];
  for (const seed of SEEDS) {
    const next = seededRandom(seed);
    const draws = Array.from({ length: DRAWS }, () => String(next()));
    lines.push(["random", String(seed >>> 0), ...draws].join(" "));
  }
  lines.push(
    "# shuffle <seed> <length> <permutation>: shuffled(0..length, seededRandom(seed)), comma-separated.",
  );
  for (const seed of SEEDS) {
    for (const length of SHUFFLE_LENGTHS) {
      const items = Array.from({ length }, (_, i) => i);
      const out = shuffled(items, seededRandom(seed));
      lines.push(
        [
          "shuffle",
          String(seed >>> 0),
          String(length),
          out.join(",") || "-",
        ].join(" "),
      );
    }
  }
  return lines;
}

function printBudget() {
  const lines = [
    HEADER,
    "# budget <effort> <field>=<count>...: budgetOf({ effort }) in the field order of budget.ts.",
  ];
  for (const effort of ["fast", "balanced", "thorough"]) {
    const budget = budgetOf({ effort });
    const fields = Object.entries(budget).map(
      ([name, count]) => `${name}=${count}`,
    );
    lines.push(["budget", effort, ...fields].join(" "));
  }
  const fallback = budgetOf({});
  lines.push(
    [
      "budget",
      "unset",
      ...Object.entries(fallback).map(([name, count]) => `${name}=${count}`),
    ].join(" "),
  );
  return lines;
}

function hex(bytes) {
  return Buffer.from(bytes).toString("hex");
}

function printFrame() {
  return [
    HEADER,
    "# frame <kind> <hex>: the columnar frame of the golden graph or layout (frameGolden.ts), lowercase hex.",
    `frame graph ${hex(encodeGraph(goldenGraph))}`,
    `frame layout ${hex(encodeLayout(goldenLayout))}`,
    `frame empty-layout ${hex(encodeLayout(emptyLayout))}`,
  ];
}

const SOLVE_PROBLEMS = 2000;

/**
 * The random problem `seed`: a DAG of up to 25 variables, with every fourth seed on integer targets and gaps, so ties
 * and degenerate blocks come up. The Rust test regenerates it from the same draws, in the same order, so only the
 * solver's output is printed.
 */
function randomProblem(seed) {
  const random = seededRandom(seed);
  const n = 2 + Math.floor(random() * 24);
  const integral = seed % 4 === 0;
  const x0 = Array.from({ length: n }, () =>
    integral ? Math.floor(random() * 10) : random() * 100 - 50,
  );
  const weight = Array.from({ length: n }, () => 0.5 + random() * 2);
  const count = Math.floor(random() * (3 * n));
  const seps = [];
  for (let k = 0; k < count; k++) {
    let a = Math.floor(random() * n);
    let b = Math.floor(random() * n);
    if (a === b) {
      continue;
    }
    if (a > b) {
      [a, b] = [b, a];
    }
    const gap = integral ? Math.floor(random() * 5) - 2 : random() * 10 - 2;
    seps.push({ from: a, to: b, gap });
  }
  return { x0, weight, seps };
}

const csv = (xs) => (xs.length > 0 ? xs.map(String).join(",") : "-");

function printSolveCases() {
  const lines = [
    HEADER,
    "# case <name> <desired> <weight> <seps> <expected> <goal> <ts>: a MSAGL case (msaglCases.ts, msaglChains.ts), fields tab-separated; lists comma-separated; seps are from:to:gap joined by ';'; '-' is empty; ts is solveSeparations' output.",
  ];
  for (const c of [...cases, ...chainCases]) {
    const weight = c.weight ?? c.desired.map(() => 1);
    const seps = c.seps.map(([from, to, gap]) => ({ from, to, gap }));
    const x = solveSeparations(c.desired, weight, seps);
    lines.push(
      [
        "case",
        c.name,
        csv(c.desired),
        c.weight ? csv(c.weight) : "-",
        c.seps.length > 0
          ? c.seps.map(([from, to, gap]) => `${from}:${to}:${gap}`).join(";")
          : "-",
        csv(c.expected),
        c.goal === undefined ? "-" : String(c.goal),
        csv(x),
      ].join("\t"),
    );
  }
  return lines;
}

function printSolveRandom() {
  const lines = [
    HEADER,
    `# problem <seed> <ts>: solveSeparations of randomProblem(seed), seeds 0..${SOLVE_PROBLEMS - 1}, fields tab-separated; ts is the solution, comma-separated.`,
  ];
  for (let seed = 0; seed < SOLVE_PROBLEMS; seed++) {
    const { x0, weight, seps } = randomProblem(seed);
    lines.push(
      ["problem", String(seed), csv(solveSeparations(x0, weight, seps))].join(
        "\t",
      ),
    );
  }
  return lines;
}

const sections = {
  random: printRandom,
  budget: printBudget,
  frame: printFrame,
  "solve-cases": printSolveCases,
  "solve-random": printSolveRandom,
};
const which = process.argv[2];
if (!(which in sections)) {
  process.stderr.write(
    `usage: print-fixtures.mjs ${Object.keys(sections).join("|")}\n`,
  );
  process.exit(2);
}
process.stdout.write(`${sections[which]().join("\n")}\n`);
