// Prints the TypeScript oracle values that the Rust crates are tested against. Contributor
// tooling only: it runs under Node's type stripping, imports the TypeScript sources directly, and writes to stdout.
//
//   mise exec -- node scripts/parity/print-fixtures.mjs random > crates/graph-layout/fixtures/parity/random.txt
//   mise exec -- node scripts/parity/print-fixtures.mjs budget > crates/graph-layout/fixtures/parity/budget.txt
//
// The fixtures are committed; regenerate them only when the TypeScript source changes on purpose.

import { budgetOf } from "../../packages/graph-layout/src/budget.ts";
import {
  seededRandom,
  shuffled,
} from "../../packages/graph-layout/src/random.ts";

const HEADER =
  "# Generated by scripts/parity/print-fixtures.mjs from packages/graph-layout/src. Do not edit by hand.";

// Seeds as the TypeScript functions see them after `seed >>> 0`: the Rust side takes the same u32.
const SEEDS = [0, 1, 42, 123456789, 0x9e3779b9, 0x7fffffff, 0xffffffff];
const DRAWS = 16;
const SHUFFLE_LENGTHS = [0, 1, 2, 7, 64];

function printRandom() {
  const lines = [
    HEADER,
    "# random <seed> <draw>...: each draw is String(x) of seededRandom(seed)() in [0, 1).",
  ];
  for (const seed of SEEDS) {
    const next = seededRandom(seed);
    const draws = Array.from({ length: DRAWS }, () => String(next()));
    lines.push(["random", String(seed >>> 0), ...draws].join(" "));
  }
  lines.push(
    "# shuffle <seed> <length> <permutation>: shuffled(0..length, seededRandom(seed)), comma-separated.",
  );
  for (const seed of SEEDS) {
    for (const length of SHUFFLE_LENGTHS) {
      const items = Array.from({ length }, (_, i) => i);
      const out = shuffled(items, seededRandom(seed));
      lines.push(
        [
          "shuffle",
          String(seed >>> 0),
          String(length),
          out.join(",") || "-",
        ].join(" "),
      );
    }
  }
  return lines;
}

function printBudget() {
  const lines = [
    HEADER,
    "# budget <effort> <field>=<count>...: budgetOf({ effort }) in the field order of budget.ts.",
  ];
  for (const effort of ["fast", "balanced", "thorough"]) {
    const budget = budgetOf({ effort });
    const fields = Object.entries(budget).map(
      ([name, count]) => `${name}=${count}`,
    );
    lines.push(["budget", effort, ...fields].join(" "));
  }
  const fallback = budgetOf({});
  lines.push(
    [
      "budget",
      "unset",
      ...Object.entries(fallback).map(([name, count]) => `${name}=${count}`),
    ].join(" "),
  );
  return lines;
}

const sections = { random: printRandom, budget: printBudget };
const which = process.argv[2];
if (!(which in sections)) {
  process.stderr.write(
    `usage: print-fixtures.mjs ${Object.keys(sections).join("|")}\n`,
  );
  process.exit(2);
}
process.stdout.write(`${sections[which]().join("\n")}\n`);
