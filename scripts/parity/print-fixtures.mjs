const SOLVE_PROBLEMS = 2000;

/**
 * The random problem `seed`: a DAG of up to 25 variables, with every fourth seed on integer targets and gaps, so ties
 * and degenerate blocks come up. The Rust test regenerates it from the same draws, in the same order, so only the
 * solver's output is printed.
 */
function randomProblem(seed) {
  const random = seededRandom(seed);
  const n = 2 + Math.floor(random() * 24);
  const integral = seed % 4 === 0;
  const x0 = Array.from({ length: n }, () =>
    integral ? Math.floor(random() * 10) : random() * 100 - 50,
  );
  const weight = Array.from({ length: n }, () => 0.5 + random() * 2);
  const count = Math.floor(random() * (3 * n));
  const seps = [];
  for (let k = 0; k < count; k++) {
    let a = Math.floor(random() * n);
    let b = Math.floor(random() * n);
    if (a === b) {
      continue;
    }
    if (a > b) {
      [a, b] = [b, a];
    }
    const gap = integral ? Math.floor(random() * 5) - 2 : random() * 10 - 2;
    seps.push({ from: a, to: b, gap });
  }
  return { x0, weight, seps };
}

function printSolveCases() {
  const lines = [
    HEADER,
    "# case <name> <desired> <weight> <seps> <expected> <goal> <ts>: a MSAGL case (msaglCases.ts, msaglChains.ts), fields tab-separated; lists comma-separated; seps are from:to:gap joined by ';'; '-' is empty; ts is solveSeparations' output as the hex of each value's IEEE 754 bits (16 digits).",
  ];
  for (const c of [...cases, ...chainCases]) {
    const weight = c.weight ?? c.desired.map(() => 1);
    const seps = c.seps.map(([from, to, gap]) => ({ from, to, gap }));
    const x = solveSeparations(c.desired, weight, seps);
    lines.push(
      [
        "case",
        c.name,
        csv(c.desired),
        c.weight ? csv(c.weight) : "-",
        c.seps.length > 0
          ? c.seps.map(([from, to, gap]) => `${from}:${to}:${gap}`).join(";")
          : "-",
        csv(c.expected),
        c.goal === undefined ? "-" : String(c.goal),
        bitsCsv(x),
      ].join("\t"),
    );
  }
  return lines;
}

function printSolveRandom() {
  const lines = [
    HEADER,
    `# problem <seed> <ts>: solveSeparations of randomProblem(seed), seeds 0..${SOLVE_PROBLEMS - 1}, fields tab-separated; ts is the solution, comma-separated, each value as the hex of its IEEE 754 bits (16 digits).`,
  ];
  for (let seed = 0; seed < SOLVE_PROBLEMS; seed++) {
    const { x0, weight, seps } = randomProblem(seed);
    lines.push(
      [
        "problem",
        String(seed),
        bitsCsv(solveSeparations(x0, weight, seps)),
      ].join("\t"),
    );
  }
  return lines;
}

const LAYERING_DAGS = 200;
const LAYERING_RANDOM = 300;
const LAYERING_KINDS = {
  dependency: { ranks: true },
  heavy: { ranks: true, weight: 4 },
  stretched: { ranks: true, minLength: 2 },
  info: { ranks: false, weight: 0.5 },
};
// `unknown` has no policy in LAYERING_KINDS: it does not rank, with minLength 1 and weight 1.
const LAYERING_KIND_NAMES = [...Object.keys(LAYERING_KINDS), "unknown"];
const LAYERING_MODES = ["none", "soft", "strict"];

/** A graph of `count` nodes from the seed: DAGs for the first `LAYERING_DAGS` seeds, then graphs with cycles and loops. */
function randomLayering(seed) {
  const random = seededRandom(seed);
  const dag = seed < LAYERING_DAGS;
  const count = 2 + Math.floor(random() * 15);
  const nodes = Array.from({ length: count }, (_, i) => {
    // A node in no band is free: under strict partitions it counts as band 0 (rank/index.ts).
    const band = random() < 0.2 ? undefined : Math.floor(random() * 3);
    return {
      id: `n${i}`,
      width: 60,
      height: 30,
      ...(band === undefined ? {} : { partition: band }),
    };
  });
  const edges = [];
  const edgeCount = Math.floor(random() * 3 * count);
  for (let k = 0; k < edgeCount; k++) {
    let a = Math.floor(random() * count);
    let b = Math.floor(random() * count);
    if (dag) {
      if (a === b) {
        continue;
      }
      if (a > b) {
        [a, b] = [b, a];
      }
    }
    const kind =
      LAYERING_KIND_NAMES[Math.floor(random() * LAYERING_KIND_NAMES.length)];
    edges.push({ id: `e${k}`, source: `n${a}`, target: `n${b}`, kind });
  }
  return {
    name: `random-${dag ? "dag" : "cyclic"}-${seed}`,
    graph: { nodes, edges },
    options: {
      direction: "down",
      edgeKinds: LAYERING_KINDS,
      partitions: LAYERING_MODES[seed % LAYERING_MODES.length],
    },
  };
}

function printLayering() {
  const golden = {
    direction: "down",
    edgeKinds: { lineage: { ranks: true }, ref: { ranks: false } },
  };
  // Negative zero is a band of its own bits and the same band as +0 under ===: TypeScript keys bands by value.
  const negativeZero = {
    nodes: [
      { id: "n0", width: 60, height: 30, partition: -0 },
      { id: "n1", width: 60, height: 30, partition: 0 },
      { id: "n2", width: 60, height: 30, partition: 1 },
      { id: "n3", width: 60, height: 30 },
    ],
    edges: [
      { id: "e0", source: "n0", target: "n2", kind: "dependency" },
      { id: "e1", source: "n1", target: "n2", kind: "dependency" },
      { id: "e2", source: "n2", target: "n3", kind: "dependency" },
    ],
  };
  const cases = [
    { name: "banded", graph: bandedGraph, options: bandedOptions },
    { name: "golden", graph: goldenGraph, options: golden },
    {
      name: "negative-zero-soft",
      graph: negativeZero,
      options: {
        direction: "down",
        edgeKinds: LAYERING_KINDS,
        partitions: "soft",
      },
    },
    {
      name: "negative-zero-strict",
      graph: negativeZero,
      options: {
        direction: "down",
        edgeKinds: LAYERING_KINDS,
        partitions: "strict",
      },
    },
  ];
  for (let seed = 0; seed < LAYERING_RANDOM; seed++) {
    cases.push(randomLayering(seed));
  }
  return [
    HEADER,
    "# case <name> <mode> <bands> <edges> <ranks> <reversed> <chains>: rank and layer of the graph without ports or clusters (see layeringLine in scripts/parity/layering-graphs.mjs); floats as IEEE bits.",
    ...cases.map((c) =>
      layeringLine(c.name, c.graph, { options: c.options, rank, layer }),
    ),
  ];
}

function printLayeringFinance(manifestPath) {
  if (manifestPath === undefined) {
    process.stderr.write(
      "usage: print-fixtures.mjs layering-finance <manifest.json>\n",
    );
    process.exit(2);
  }
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  return [
    HEADER,
    "# case <name> <mode> <bands> <edges> <ranks> <reversed> <chains>: the finance lineage graph (scripts/parity/finance-graph.mjs) without clusters.",
    layeringLine("finance", financeGraph(manifest), {
      options: LINEAGE_OPTIONS,
      rank,
      layer,
    }),
  ];
}

